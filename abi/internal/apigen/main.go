// Command apigen generates typed bindings from ordered declarations extracted
// from the upstream default ABI headers.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"regexp"
	"strings"
	"text/template"
)

var (
	declaration = regexp.MustCompile(`^(.+?)\s*\(\*([a-z_]+)\)\((.*)\);$`)
	argument    = regexp.MustCompile(`^(.+?)\s+([a-z_]+)(\[\])?$`)
	flavored    = regexp.MustCompile(`RIME_FLAVORED\((\w+)\)`)
)

type slot struct {
	CName     string
	GoName    string
	Signature string
}

type table struct {
	Name  string
	CName string
	Slots []slot
}

func main() {
	log.SetFlags(0)
	for _, spec := range []struct{ name, cName, input, output string }{
		{"API", "RimeApi", "api.txt", "api"},
		{"LeversAPI", "RimeLeversApi", "levers.txt", "levers"},
	} {
		input, err := os.Open("internal/apigen/" + spec.input)
		if err != nil {
			log.Fatal(err)
		}
		slots, err := readSlots(input)
		input.Close()
		if err != nil {
			log.Fatalf("%s: %v", spec.input, err)
		}
		data := table{spec.name, spec.cName, slots}
		write(spec.output+"_generated.go", data)
	}
}

func write(path string, data table) {
	var buf bytes.Buffer
	if err := template.Must(template.New("file").Parse(binding)).Execute(&buf, data); err != nil {
		log.Fatal(err)
	}
	output, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format %s: %v", path, err)
	}
	if err := os.WriteFile(path, output, 0644); err != nil {
		log.Fatal(err)
	}
}

func readSlots(r io.Reader) ([]slot, error) {
	var slots []slot
	seen := map[string]bool{}
	scanner := bufio.NewScanner(r)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := declaration.FindStringSubmatch(line)
		if parts == nil {
			return nil, fmt.Errorf("invalid declaration %q", line)
		}
		name := parts[2]
		if seen[name] {
			return nil, fmt.Errorf("duplicate slot %q", name)
		}
		seen[name] = true
		ret, err := goType(parts[1])
		if err != nil {
			return nil, err
		}
		var args []string
		if parts[3] != "" && parts[3] != "void" {
			for a := range strings.SplitSeq(parts[3], ",") {
				arg := argument.FindStringSubmatch(strings.TrimSpace(a))
				if arg == nil {
					return nil, fmt.Errorf("invalid argument %q in %s", a, name)
				}
				cType := arg[1]
				if arg[3] != "" {
					cType += "*"
				}
				goArg, err := goType(cType)
				if err != nil {
					return nil, err
				}
				if name == "set_notification_handler" && arg[2] == "context_object" {
					goArg = "uintptr"
				}
				args = append(args, lowerCamel(arg[2])+" "+goArg)
			}
		}
		slots = append(slots, slot{name, camel(name), "func(" + strings.Join(args, ", ") + ") " + ret})
	}
	if len(slots) == 0 && scanner.Err() == nil {
		return nil, fmt.Errorf("table has no function slots")
	}
	return slots, scanner.Err()
}

var cTypes = map[string]string{
	"void": "", "void*": "unsafe.Pointer", "RIME_PROTO_BUILDER*": "unsafe.Pointer",
	"Bool": "Bool", "Bool*": "*Bool", "int": "int32", "int*": "*int32",
	"double": "float64", "double*": "*float64", "size_t": "uintptr",
	"char*": "*byte", "char**": "**byte", "RimeSessionId": "SessionID",
	"RimeNotificationHandler": "uintptr", "RimeStringSlice": "StringSlice",
	"RimeTraits*": "*Traits", "RimeCommit*": "*Commit", "RimeContext*": "*Context",
	"RimeStatus*": "*Status", "RimeSchemaList*": "*SchemaList", "RimeConfig*": "*Config",
	"RimeConfigIterator*": "*ConfigIterator", "RimeModule*": "*Module",
	"RimeCandidateListIterator*": "*CandidateListIterator", "RimeCandidatePreview*": "*CandidatePreview",
	"RimeCustomSettings*": "*CustomSettings", "RimeSwitcherSettings*": "*SwitcherSettings",
	"RimeSchemaInfo*": "*SchemaInfo", "RimeUserDictIterator*": "*UserDictIterator",
}

func goType(cType string) (string, error) {
	cType = flavored.ReplaceAllString(strings.TrimPrefix(strings.TrimSpace(cType), "const "), "$1")
	cType = strings.ReplaceAll(cType, " ", "")
	if result, ok := cTypes[cType]; ok {
		return result, nil
	}
	return "", fmt.Errorf("unknown C type %q", cType)
}

func camel(name string) string {
	var result strings.Builder
	for part := range strings.SplitSeq(name, "_") {
		switch part {
		case "id", "api":
			result.WriteString(strings.ToUpper(part))
		case "cstring":
			result.WriteString("CString")
		default:
			result.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return result.String()
}

func lowerCamel(name string) string {
	first, rest, found := strings.Cut(name, "_")
	if found {
		return first + camel(rest)
	}
	return first
}

const binding = `// Code generated by go generate; DO NOT EDIT.

package abi

import "unsafe"

// {{.Name}} is the callable view of the default C {{.CName}} table. Unavailable
// fields are nil. Callers must stop using this view before unloading its library.
type {{.Name}} struct {
	capabilities map[string]Capability
{{- range .Slots}}
	// {{.GoName}} is the C {{.CName}} slot.
	{{.GoName}} {{.Signature}}
{{- end}}
}

type raw{{.Name}} struct {
	DataSize int32
{{- range .Slots}}
	{{.GoName}} uintptr
{{- end}}
}

// Capability reports the status of a slot named by its exact C spelling.
func (a *{{.Name}}) Capability(cName string) Capability {
	if a == nil {
		return CapabilityUnknown
	}
	return a.capabilities[cName]
}

// Available reports whether a slot named by its exact C spelling can be called.
func (a *{{.Name}}) Available(cName string) bool { return a.Capability(cName) == CapabilityAvailable }

// Slots lists the C names recognized by this binding in ABI order.
func (*{{.Name}}) Slots() []string {
	return []string{
{{- range .Slots}}
		"{{.CName}}",
{{- end}}
	}
}

func bind{{.Name}}(native tableView) *{{.Name}} {
	a := &{{.Name}}{capabilities: make(map[string]Capability)}
	var layout raw{{.Name}}
{{- range .Slots}}
	a.capabilities["{{.CName}}"] = native.bind(unsafe.Offsetof(layout.{{.GoName}}), &a.{{.GoName}})
{{- end}}
	return a
}
`
